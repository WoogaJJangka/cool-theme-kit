/**
 * Writes the folder icons of `./folderBadges.ts`: `assets/icons/folders/<name>.svg` and
 * `assets/icons/foldersOpen/<name>.svg`, each the folder shape of the icon plugin in a color with the shape of a file
 * icon as its badge. Run `bun run sync:metrics` afterwards.
 *
 * Usage: bun run sync:folders
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { luminance, mixColors, parseSvg } from 'src/icons/glass/glassIcons';

import { FOLDER_BADGES } from './folderBadges';
import { measureBox } from './iconMetrics';

import type { FolderBadge } from './folderBadges';

const root = join(__dirname, '..', '..', '..');

/** The folders of `assets/icons` the icons are written to: closed, and expanded */
type FolderGroup = 'folders' | 'foldersOpen';

/**
 * The folder shapes of the folder icons of the plugin (iconGenerator `folders/src.svg` and `foldersOpen/src.svg`),
 * in their 24 unit canvas
 */
const SHAPES: Record<FolderGroup, string> = {
  folders: 'm10 4h-6c-1.11 0-2 0.89-2 2v12c0 1.097 0.903 2 2 2h16c1.097 0 2-0.903 2-2v-10c0-1.11-0.9-2-2-2h-8l-2-2z',
  foldersOpen: 'M20,18H4V8H20M20,6H12L10,4H4C2.89,4 2,4.89 2,6V18A2,2 0 0,0 4,20H20A2,2 0 0,0 22,18V8C22,6.89 21.1,6 20,6Z',
};

/** Where the plugin draws the badge of a folder: the center of its box, and the size a badge fits in */
const BADGE = { height: 10.6, width: 12.4, x: 16.2, y: 15.4 };

const PAINT = /((?:fill|stroke|stop-color)\s*[:=][\s"']*)(#[\dA-Fa-f]{6}|#[\dA-Fa-f]{3})(?![\dA-Fa-f])/g;

const round = (value: number) => Number(value.toFixed(4));

const FOLDER_NOTICE =
  '<!-- Generated by `bun run sync:folders` (src/scripts/icons/folderBadges.ts) from the icons of iconGenerator (MIT, ' +
  'Copyright (c) 2015-2024 Elior "Mallowigi" Boukhobza) and of JetBrains/intellij-community (Apache License 2.0): ' +
  'see assets/icons/NOTICE.md. Do not edit. -->\n';

/** The color of a badge on its folder, as the plugin picks them: a light tint on a folder, a dark shade on a light one */
const badgeColor = (color: string) => (luminance(color) > 0.4 ? mixColors(color, '#000000', 0.55) : mixColors(color, '#ffffff', 0.72));

/** The file icon a badge takes its shape from: the fork's own icon of a name wins, as in the generator */
const glyphOf = (repository: string, { from = 'files', glyph }: FolderBadge): string => {
  const icons = join(repository, 'assets', 'icons');
  const folders = from === 'glass' ? [join(icons, 'glass', 'files')] : [join(repository, 'iconGenerator', 'assets', 'icons', 'files'), join(icons, 'files')];
  const file = folders.map((folder) => join(folder, `${glyph}.svg`)).findLast((path) => existsSync(path));
  if (!file) throw new Error(`${glyph}: no such ${from} icon`);
  // the same icon whatever line ends git gave the checkout of this machine
  return readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
};

/**
 * A folder icon of this fork: the folder shape in the color of the badge table, and the shape of a file icon in one
 * color in the box of the badge.
 * @param glyph the svg of the file icon
 */
const folderIcon = (badge: FolderBadge, glyph: string, group: FolderGroup): string => {
  const parts = parseSvg(glyph);
  const box = measureBox(glyph);
  if (!parts || !box) throw new Error(`${badge.glyph}: nothing to draw`);

  const color = badgeColor(badge.color);
  const scale = Math.min(BADGE.width / box[2], BADGE.height / box[3]);
  const transform = `translate(${round(BADGE.x - scale * (box[0] + box[2] / 2))} ${round(BADGE.y - scale * (box[1] + box[3] / 2))}) scale(${round(scale)})`;
  const recolor = (text: string) => text.replaceAll(PAINT, (_, paint: string) => `${paint}${color}`);

  return (
    `${FOLDER_NOTICE}<svg xmlns="http://www.w3.org/2000/svg"${parts.namespaces} viewBox="0 0 24 24" width="16px" height="16px">` +
    `<path d="${SHAPES[group]}" fill="${badge.color}" data-folderColor="${badge.name}"/>` +
    // what has no paint of its own would be drawn black: the group gives it the color
    `<g fill="${color}" data-folderIconColor="${badge.name}" transform="${transform}"><g ${recolor(parts.attributes)}>${recolor(parts.content)}</g></g>` +
    '</svg>\n'
  );
};

/** Every folder icon of the badge table, by its path in `assets/icons`: `folders/claude.svg` */
const folderIcons = (repository: string): Map<string, string> => {
  const icons = new Map<string, string>();
  for (const group of Object.keys(SHAPES) as FolderGroup[]) {
    for (const badge of FOLDER_BADGES) icons.set(`${group}/${badge.name}.svg`, folderIcon(badge, glyphOf(repository, badge), group));
  }
  return icons;
};

if (require.main === module) {
  const icons = folderIcons(root);
  for (const group of Object.keys(SHAPES)) {
    const folder = join(root, 'assets', 'icons', group);
    mkdirSync(folder, { recursive: true });
    // the icons of the names taken out of the table
    for (const file of readdirSync(folder).filter((item) => !icons.has(`${group}/${item}`))) rmSync(join(folder, file));
  }
  for (const [path, icon] of icons) writeFileSync(join(root, 'assets', 'icons', path), icon);
  console.log(`assets/icons/folders, assets/icons/foldersOpen: ${FOLDER_BADGES.length} folder icons`);
}

export { FOLDER_NOTICE, folderIcon, folderIcons };
export type { FolderGroup };
