/**
 * The license texts of the npm packages bundled into the extension code, in THIRD-PARTY-NOTICES.md.
 *
 * The VSIX has no node_modules (`vsce package --no-dependencies`) and the minified bundle keeps no comments of those
 * packages, so their copyright and license notices reach the users only through this part of THIRD-PARTY-NOTICES.md,
 * between the two markers. It is generated from the installed packages that esbuild bundles (test/checks/bundledPackages.js).
 *
 * Usage: `bun run check:notices` fails when the part is not what the bundled packages give (a package added or removed,
 * a license changed by an update); `bun run sync:notices` writes it.
 */
const { existsSync, readdirSync, readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

const { bundledPackages, root } = require('./bundledPackages');

const NOTICES = join(root, 'THIRD-PARTY-NOTICES.md');
const START = '<!-- bundled-packages:start: generated by `bun run sync:notices` from the bundled packages, do not edit -->';
const END = '<!-- bundled-packages:end -->';
const LICENSE_FILE = /^(?:licen[cs]e|copying)(?:[.-].*)?$/i;

/** Code unit order, the same on every platform and locale */
const compare = (a, b) => {
  if (a < b) return -1;
  return a > b ? 1 : 0;
};

/** The license file of a package folder: LICENSE, LICENSE.md, LICENCE.txt… */
const licenseText = (name, folder) => {
  const file = readdirSync(folder).filter((entry) => LICENSE_FILE.test(entry)).sort(compare)[0];
  if (!file) throw new Error(`${name} has no license file in ${folder}: add its license to THIRD-PARTY-NOTICES.md by hand`);
  return readFileSync(join(folder, file), 'utf8')
    .replaceAll('\r\n', '\n')
    .split('\n')
    .map((line) => line.replaceAll('\t', '    ').trimEnd())
    .join('\n')
    .trim();
};

/** The license id of a package.json: `license`, or the old `licenses` list */
const licenseId = (manifest) => {
  if (typeof manifest.license === 'string') return manifest.license;
  if (manifest.license?.type) return manifest.license.type;
  if (Array.isArray(manifest.licenses)) return manifest.licenses.map((license) => license.type ?? license).join(' OR ');
  return 'see the license text';
};

/** The generated part, between the markers */
const generate = () => {
  const packages = [...bundledPackages()].sort(([a], [b]) => compare(a, b));
  const lines = [
    START,
    '## npm packages in the extension code',
    '',
    'The bundled code of the extension (`dist/extension.js`) contains these npm packages. The extension package has no',
    '`node_modules` folder, so their license texts are here.',
    '',
    '| Package | License |',
    '|---|---|',
  ];
  const texts = [];
  for (const [name, copies] of packages) {
    const licenses = new Map();
    for (const folder of copies.values()) {
      const manifest = JSON.parse(readFileSync(join(folder, 'package.json'), 'utf8'));
      licenses.set(licenseText(name, folder), licenseId(manifest));
    }
    lines.push(`| [${name}](https://www.npmjs.com/package/${name}) | ${[...new Set(licenses.values())].join(', ')} |`);
    for (const text of licenses.keys()) texts.push('', `### ${name}`, '', '```text', text, '```');
  }
  if (packages.length === 0) lines.push('| (none) | |');
  lines.push(...texts, END);
  return lines.join('\n');
};

/** The current part of THIRD-PARTY-NOTICES.md, the text around it */
const current = () => {
  const text = readFileSync(NOTICES, 'utf8').replaceAll('\r\n', '\n');
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`THIRD-PARTY-NOTICES.md has no generated part: put the two lines\n${START}\n${END}\nwhere it goes`);
  }
  return { after: text.slice(end + END.length), before: text.slice(0, start), part: text.slice(start, end + END.length) };
};

const main = () => {
  if (!existsSync(join(root, 'node_modules'))) throw new Error('node_modules is missing: run `bun install` first');
  const expected = generate();
  const { after, before, part } = current();
  if (process.argv.includes('--write')) {
    if (part === expected) {
      console.log('THIRD-PARTY-NOTICES.md is up to date.');
      return;
    }
    writeFileSync(NOTICES, `${before}${expected}${after}`);
    console.log('THIRD-PARTY-NOTICES.md written.');
    return;
  }
  if (part !== expected) {
    console.log('::error title=Third-party notices::THIRD-PARTY-NOTICES.md does not have the licenses of the bundled packages: run `bun run sync:notices`');
    console.error('Run `bun run sync:notices` and commit THIRD-PARTY-NOTICES.md (a bundled package was added, removed or changed its license).');
    process.exitCode = 1;
    return;
  }
  console.log('THIRD-PARTY-NOTICES.md has the licenses of the bundled packages.');
};

try {
  main();
} catch (error) {
  console.error(error);
  process.exitCode = 1;
}
